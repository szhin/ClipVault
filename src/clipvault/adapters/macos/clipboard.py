"""Đọc/ghi clipboard macOS (NSPasteboard qua pyobjc). CHƯA kiểm chứng trên máy thật (phát triển trên Windows).

Giữ nguyên bytes như OS trả về. Phần chọn định dạng (`select_types`) là hàm thuần để test không cần macOS;
pyobjc chỉ được import khi tạo reader/writer. macOS không cho biết kích thước trước khi lấy NSData, nên
giới hạn mục được kiểm tra sau từng định dạng (vượt thì dừng ngay, không lấy tiếp các định dạng còn lại).
"""

from __future__ import annotations

import time
from collections.abc import Sequence
from dataclasses import dataclass

from clipvault.core.model import Representation, Snapshot
from clipvault.core.ports import ClipboardUnavailable, ClipboardWriteError, ItemTooLarge

UTI_TEXT = "public.utf8-plain-text"
UTI_PNG = "public.png"
UTI_TIFF = "public.tiff"

# Cờ riêng tư theo quy ước nspasteboard.org (password manager, dữ liệu tạm): có là không lưu mục đó.
PRIVACY_TYPES = frozenset({
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
})


@dataclass(frozen=True)
class TypeSpec:
    uti: str
    native_format: str
    mime: str


def select_types(available: Sequence[str]) -> list[TypeSpec] | None:
    """Chọn UTI theo allowlist, giữ thứ tự OS liệt kê. None nếu nguồn đánh dấu riêng tư; [] nếu không có gì."""
    if any(t in PRIVACY_TYPES for t in available):
        return None
    has_png = UTI_PNG in available
    chosen: list[TypeSpec] = []
    for uti in available:
        if uti == UTI_TEXT:
            chosen.append(TypeSpec(uti, uti, "text/plain"))
        elif uti == UTI_PNG:
            chosen.append(TypeSpec(uti, uti, "image/png"))
        elif uti == UTI_TIFF and not has_png:  # TIFF thường là bản tổng hợp của PNG: chỉ giữ khi không có PNG
            chosen.append(TypeSpec(uti, uti, "image/tiff"))
    return chosen


def _pasteboard():
    try:
        from AppKit import NSPasteboard
    except ImportError as exc:  # thiếu pyobjc
        raise ClipboardUnavailable("pyobjc (AppKit) is not available") from exc
    return NSPasteboard.generalPasteboard()


class MacClipboardReader:
    def __init__(self) -> None:
        self._pb = _pasteboard()

    def sequence_number(self) -> int | None:
        return int(self._pb.changeCount())

    def read_snapshot(self, max_item_bytes: int) -> Snapshot | None:
        available = [str(t) for t in (self._pb.types() or [])]
        chosen = select_types(available)
        if not chosen:
            return None
        sequence = self.sequence_number()
        reps: list[Representation] = []
        total = 0
        for spec in chosen:
            nsdata = self._pb.dataForType_(spec.uti)
            if nsdata is None:
                continue
            data = bytes(nsdata)
            total += len(data)
            if total > max_item_bytes:
                raise ItemTooLarge(total, [s.native_format for s in chosen])
            reps.append(Representation(spec.native_format, spec.mime, data))
        if not reps:
            return None
        return Snapshot(tuple(reps), None, time.time_ns() // 1_000_000, sequence)


class MacClipboardWriter:
    """Ghi lại đúng từng (UTI, bytes) theo thứ tự đã lưu (paste-back)."""

    def __init__(self) -> None:
        self._pb = _pasteboard()

    def write(self, representations: Sequence[Representation]) -> int | None:
        if not representations:
            raise ClipboardWriteError("nothing to write")
        from Foundation import NSData

        self._pb.clearContents()
        for rep in representations:
            nsdata = NSData.dataWithBytes_length_(rep.data, len(rep.data))
            if not self._pb.setData_forType_(nsdata, rep.native_format):
                raise ClipboardWriteError(f"setData failed: {rep.native_format}")
        return int(self._pb.changeCount())
